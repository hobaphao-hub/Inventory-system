EXPIRY_SIGNATURE_FILE = "email_expiry_signature.json"


def load_expiry_signature():
    if os.path.exists(EXPIRY_SIGNATURE_FILE):
        try:
            with open(EXPIRY_SIGNATURE_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                return data.get("signature", "")
        except Exception:
            return ""
    return ""


def save_expiry_signature(signature: str):
    try:
        with open(EXPIRY_SIGNATURE_FILE, "w", encoding="utf-8") as f:
            json.dump({"signature": signature}, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


