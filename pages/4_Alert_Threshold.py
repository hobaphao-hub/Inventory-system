def build_lot_expiry_alerts(df_products, days_threshold=60):
    """
    Tạo bảng cảnh báo lô hàng sắp hết hạn sử dụng (HSD còn dưới days_threshold ngày).
    Đọc trực tiếp từ warehouse_areas.csv để đảm bảo số lô và số lượng khớp với trang Khu Vực Kho.
    Bỏ logic FEFO, chỉ đọc số lượng còn lại từ warehouse_areas.csv.
    """
    import_db_path = "database/phieu_nhap.csv"
    export_db_path = "database/phieu_xuat.csv"
    warehouse_areas_path = "database/warehouse_areas.csv"
    
    # Đọc warehouse_areas.csv - đây là nguồn dữ liệu chính
    warehouse_assignments = pd.DataFrame()
    if os.path.exists(warehouse_areas_path):
        try:
            warehouse_assignments = pd.read_csv(warehouse_areas_path)
            if not warehouse_assignments.empty:
                warehouse_assignments["Mã sản phẩm"] = warehouse_assignments["Mã sản phẩm"].astype(str)
                warehouse_assignments["Lô"] = pd.to_numeric(warehouse_assignments["Lô"], errors="coerce").fillna(0).astype(int)
                warehouse_assignments["Số lượng"] = pd.to_numeric(warehouse_assignments.get("Số lượng", 0), errors="coerce").fillna(0).astype(int)
                warehouse_assignments = warehouse_assignments[warehouse_assignments["Số lượng"] > 0]  # Chỉ lấy các dòng còn số lượng
        except Exception:
            warehouse_assignments = pd.DataFrame()

    if warehouse_assignments.empty:
        return pd.DataFrame()

    # Đọc phiếu nhập để lấy thông tin HSD và Ngày nhập
    if os.path.exists(import_db_path):
        df_import_all = pd.read_csv(import_db_path)
    else:
        df_import_all = pd.DataFrame()

    if os.path.exists(export_db_path):
        df_export_all = pd.read_csv(export_db_path)
    else:
        df_export_all = pd.DataFrame()

    alerts = []
    today = date.today()

    # Tạo mapping từ (Mã sản phẩm, Lô) -> thông tin từ phiếu nhập
    import_info_map = {}
    if not df_import_all.empty and "Mã sản phẩm" in df_import_all.columns:
        for ma_sp in warehouse_assignments["Mã sản phẩm"].unique():
            df_sp_imports = df_import_all[
                df_import_all["Mã sản phẩm"].astype(str) == str(ma_sp)
            ].copy()
            
            if not df_sp_imports.empty:
                # Sắp xếp theo ngày nhập
                if "Ngày nhập" in df_sp_imports.columns:
                    df_sp_imports["_dt"] = pd.to_datetime(
                        df_sp_imports["Ngày nhập"], errors="coerce", dayfirst=True
                    )
                    df_sp_imports = df_sp_imports.sort_values(by="_dt").reset_index(drop=True)
                
                # Đánh số lô theo thứ tự nhập (1, 2, 3, ...) - không có lô ảo
                for idx, row in df_sp_imports.iterrows():
                    lot_num = idx + 1  # Lô bắt đầu từ 1
                    import_info_map[(str(ma_sp), lot_num)] = {
                        "Hạn sử dụng": str(row.get("Hạn sử dụng", "")),
                        "Ngày nhập": str(row.get("Ngày nhập", "")),
                    }

    # Kiểm tra xem sản phẩm có lô ảo INIT không (để map số lô đúng)
    def has_initial_lot(ma_sp, df_products, df_imports, df_exports):
        product_row = df_products[df_products["Mã sản phẩm"].astype(str) == str(ma_sp)]
        if product_row.empty:
            return False
        try:
            current_stock = int(product_row.iloc[0].get("Số lượng tồn kho", 0))
        except Exception:
            current_stock = 0

        if "Mã sản phẩm" in df_imports.columns:
            df_imp = df_imports[df_imports["Mã sản phẩm"].astype(str) == str(ma_sp)].copy()
        else:
            df_imp = pd.DataFrame()

        if "Mã sản phẩm" in df_exports.columns:
            df_exp = df_exports[df_exports["Mã sản phẩm"].astype(str) == str(ma_sp)].copy()
        else:
            df_exp = pd.DataFrame()

        total_imported = 0
        if not df_imp.empty and "Số lượng nhập" in df_imp.columns:
            total_imported = (
                pd.to_numeric(df_imp["Số lượng nhập"], errors="coerce")
                .fillna(0)
                .astype(int)
                .sum()
            )

        total_exported = 0
        if not df_exp.empty:
            total_exported = (
                pd.to_numeric(df_exp["Số lượng xuất"], errors="coerce")
                .fillna(0)
                .astype(int)
                .sum()
            )

        initial_qty = current_stock - total_imported + total_exported
        return initial_qty > 0

    # Xử lý từng sản phẩm trong warehouse_areas.csv
    for ma_sp in warehouse_assignments["Mã sản phẩm"].unique():
        ma_sp = str(ma_sp).strip()
        if not ma_sp:
            continue

        # Lấy thông tin sản phẩm
        product_row = df_products[df_products["Mã sản phẩm"].astype(str) == ma_sp]
        if product_row.empty:
            continue
        ten_sp = product_row.iloc[0].get("Tên sản phẩm", "")

        # Kiểm tra xem có lô ảo INIT không
        has_init = has_initial_lot(ma_sp, df_products, df_import_all, df_export_all)

        # Lấy tất cả các lô của sản phẩm này từ warehouse_areas.csv
        df_sp_lots = warehouse_assignments[
            warehouse_assignments["Mã sản phẩm"] == ma_sp
        ].copy()

        # Gom nhóm theo Lô để tổng hợp số lượng từ tất cả các khu
        lot_summary = {}
        for _, row in df_sp_lots.iterrows():
            lo_warehouse = int(row["Lô"])  # Lô trong warehouse_areas.csv (1, 2, 3...)
            so_luong = int(row["Số lượng"])
            khu = str(row.get("Khu", ""))
            
            if lo_warehouse not in lot_summary:
                lot_summary[lo_warehouse] = {
                    "so_luong": 0,
                    "is_in_khu_e": False,
                }
            
            lot_summary[lo_warehouse]["so_luong"] += so_luong
            if khu == "Khu E":
                lot_summary[lo_warehouse]["is_in_khu_e"] = True

        # Tạo cảnh báo cho từng lô
        for lo_warehouse, lot_info in lot_summary.items():
            so_luong = lot_info["so_luong"]
            is_in_khu_e = lot_info["is_in_khu_e"]
            
            if so_luong <= 0:
                continue

            # Map số lô từ warehouse_areas.csv sang số lô hiển thị (có tính đến lô ảo INIT)
            if has_init:
                # Có lô ảo INIT: warehouse_areas.csv lô 1 -> hiển thị lô 2
                display_lot = lo_warehouse + 1
            else:
                # Không có lô ảo INIT: giữ nguyên
                display_lot = lo_warehouse

            # Lấy thông tin HSD và Ngày nhập từ phiếu nhập
            import_info = import_info_map.get((ma_sp, lo_warehouse), {})
            hsd_str = import_info.get("Hạn sử dụng", "")
            ngay_nhap = import_info.get("Ngày nhập", "")

            # Nếu không có HSD thì bỏ qua (không cảnh báo)
            if not hsd_str or hsd_str.strip() == "" or hsd_str.lower() == "nan":
                continue

            # Parse HSD để kiểm tra
            try:
                hsd_dt = datetime.strptime(hsd_str, "%d/%m/%Y").date()
            except Exception:
                continue

            days_to_expiry = (hsd_dt - today).days

            # Chỉ cảnh báo các lô còn < days_threshold ngày (kể cả đã quá hạn)
            if days_to_expiry > days_threshold:
                continue

            if days_to_expiry < 0:
                canh_bao_text = f"ĐÃ HẾT HẠN {-days_to_expiry} ngày"
            else:
                canh_bao_text = f"Còn {days_to_expiry} ngày"

            # Xác định trạng thái
            if is_in_khu_e:
                trang_thai = "Đã chuyển sang Khu E"
            else:
                trang_thai = "Chưa xử lí"

            # Tình trạng: luôn là "còn dư" vì đã lọc từ warehouse_areas.csv (chỉ có lô còn số lượng > 0)
            tinh_trang = f"còn dư {so_luong}"

            alerts.append(
                {
                    "Lô": display_lot,
                    "Mã sản phẩm": ma_sp,
                    "Tên sản phẩm": ten_sp,
                    "Số lượng tồn kho": so_luong,
                    "Ngày nhập": ngay_nhap,
                    "Hạn sử dụng": hsd_str,
                    "Tình trạng": tinh_trang,
                    "Cảnh báo": canh_bao_text,
                    "Trạng thái": trang_thai,
                    "_is_in_khu_e": is_in_khu_e,  # Dùng để render màu sắc
                }
            )

    if not alerts:
        return pd.DataFrame()

    return pd.DataFrame(alerts)

